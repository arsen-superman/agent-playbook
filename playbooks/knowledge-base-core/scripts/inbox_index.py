"""Generate <kb>/inbox/INDEX.md: one table per item type, newest first.

Usage:
  python inbox_index.py <inbox-dir>   rebuild for that inbox folder
  python inbox_index.py --hook        PostToolUse hook: read the tool call from stdin,
                                      rebuild only when it touched .ai/inbox/<item>.md
"""
import json
import re
import sys
from pathlib import Path

TYPES = ["bug", "todo", "chore", "question", "finding", "idea"]
HEADER = "<!-- Generated by /kb inbox_index.py — do not edit; agents skip this file. -->"


def parse(path):
    text = path.read_text(encoding="utf-8")
    meta, title = {}, path.stem
    lines = text.splitlines()
    body_from = 0
    if lines and lines[0].strip() == "---":
        for i, line in enumerate(lines[1:], 1):
            if line.strip() == "---":
                body_from = i + 1
                break
            m = re.match(r"([\w-]+):\s*(.*)$", line)
            if m:
                meta[m.group(1)] = re.sub(r"\s+#.*$", "", m.group(2)).strip()
    for line in lines[body_from:]:
        if line.startswith("# "):
            title = line[2:].strip()
            break
    return meta, title


def cell(value):
    value = (value or "").replace("|", "\\|").strip()
    return value if value else "?"


def build(inbox):
    items = []
    for f in inbox.glob("*.md"):
        if f.name == "INDEX.md":
            continue
        meta, title = parse(f)
        items.append((f.name, meta, title))
    groups = {}
    for name, meta, title in items:
        t = meta.get("type", "").split()[0] if meta.get("type") else "other"
        groups.setdefault(t if t in TYPES else "other", []).append((name, meta, title))

    out = [HEADER, "", f"# Inbox ({len(items)})", ""]
    for t in TYPES + ["other"]:
        rows = sorted(groups.get(t, []), key=lambda r: (r[1].get("created", ""), r[0]), reverse=True)
        if not rows:
            continue
        out += [f"## {t} ({len(rows)})", ""]
        is_bug = t == "bug"
        cols = ["Created", "Title"] + (["Severity"] if is_bug else []) + ["Area", "Source", "Status", "Next"]
        out += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for name, meta, title in rows:
            nxt = meta.get("next", "n/a")
            vals = [cell(meta.get("created")), f"[{cell(title)}]({name})"]
            if is_bug:
                vals.append(cell(meta.get("severity")))
            vals += [cell(meta.get("area")), cell(meta.get("source")), cell(meta.get("status", "new")), "—" if nxt in ("n/a", "") else cell(nxt)]
            out.append("| " + " | ".join(vals) + " |")
        out.append("")
    return "\n".join(out)


def rebuild(inbox):
    inbox = Path(inbox)
    if not inbox.is_dir():
        return
    target = inbox / "INDEX.md"
    content = build(inbox)
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        target.write_text(content, encoding="utf-8", newline="\n")


def from_hook():
    try:
        data = json.load(sys.stdin)
        raw = (data.get("tool_input") or {}).get("file_path", "")
    except Exception:
        return
    p = Path(raw.replace("\\", "/"))
    if p.suffix == ".md" and p.name != "INDEX.md" and p.parent.name == "inbox" and p.parent.parent.name == ".ai":
        rebuild(p.parent)


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--hook":
        from_hook()
    elif len(sys.argv) == 2:
        rebuild(sys.argv[1])
    else:
        sys.exit(__doc__)
